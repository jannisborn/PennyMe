def _row_to_geojson_feature(row: dict) -> dict:
    """Convert a machines-table row dict to a GeoJSON Feature dict."""
    props: Dict[str, Any] = {
        "name": row["name"],
        "area": row["area"],
        "address": row["address"],
        "external_url": row["external_url"] or "null",
        "internal_url": row["internal_url"] or "null",
        "machine_status": row["machine_status"],
        "id": row["id"],
        "last_updated": str(row["last_updated"]),
    }
    if row.get("multimachine", 1) != 1:
        props["multimachine"] = row["multimachine"]
    if row.get("num_coins", 4) != 4:
        props["num_coins"] = row["num_coins"]
    if row.get("paywall", False):
        props["paywall"] = row["paywall"]
    return {
        "type": "Feature",
        "geometry": {
            "type": "Point",
            "coordinates": [row["longitude"], row["latitude"]],
        },
        "properties": props,
    }


def _normalise_url(value: Optional[str]) -> Optional[str]:
    """Return None for missing/null URL strings, otherwise the raw value."""
    return None if value in (None, "null") else value


