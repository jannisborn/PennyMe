_CREATE_TABLES_SQL = """
CREATE TABLE IF NOT EXISTS machines (
    id             INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name           TEXT    NOT NULL,
    area           TEXT    NOT NULL,
    address        TEXT    NOT NULL,
    geom           geometry(Point, 4326) NOT NULL,
    machine_status TEXT    NOT NULL DEFAULT 'available',
    status TEXT    NOT NULL DEFAULT 'unvisited',
    multimachine   INTEGER NOT NULL DEFAULT 1,
    num_coins      INTEGER NOT NULL DEFAULT 4,
    paywall        BOOLEAN NOT NULL DEFAULT FALSE,
    external_url   TEXT,
    internal_url   TEXT,
    last_updated   DATE    NOT NULL
);

CREATE TABLE IF NOT EXISTS pending_changes (
    id             INTEGER   PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
    machine_id     INTEGER   REFERENCES machines(id),
    change_type    TEXT      NOT NULL DEFAULT 'update',
    name           TEXT      NOT NULL,
    area           TEXT      NOT NULL,
    address        TEXT      NOT NULL,
    latitude       REAL      NOT NULL,
    longitude      REAL      NOT NULL,
    machine_status TEXT      NOT NULL DEFAULT 'available',
    multimachine   INTEGER   NOT NULL DEFAULT 1,
    num_coins      INTEGER   NOT NULL DEFAULT 4,
    paywall        BOOLEAN   NOT NULL DEFAULT FALSE,
    external_url   TEXT,
    internal_url   TEXT,
    last_updated   DATE      NOT NULL,
    submitted_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at    TIMESTAMP,
    submitted_by   TEXT,
    change_summary TEXT      NOT NULL,
    status         TEXT      NOT NULL DEFAULT 'open',
    image_path     TEXT
);

CREATE INDEX IF NOT EXISTS machines_geom_gist ON machines USING GIST (geom);
"""


def create_tables() -> None:
    """Create the machines and pending_changes tables if they do not exist.

    Safe to call on an already-initialised database — all statements use
    ``CREATE TABLE IF NOT EXISTS``.

    Raises:
        psycopg2.Error: On any database error.
    """
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(_CREATE_TABLES_SQL)
        conn.commit()
    logger.info("Tables created (or already exist).")


# ---------------------------------------------------------------------------
# Connection
# ---------------------------------------------------------------------------


def get_connection() -> psycopg2.extensions.connection:
    """Return a new psycopg2 connection using credentials from login.json.

    Raises:
        FileNotFoundError: If login.json does not exist.
        psycopg2.OperationalError: If the database connection fails.
    """
    with open(_LOGIN_PATH, "r") as f:
        login = json.load(f)
    return psycopg2.connect(**login)


_engine = None


def get_engine():
    """Return a cached SQLAlchemy engine used by geopandas operations."""
    global _engine
    if _engine is None:
        with open(_LOGIN_PATH) as f:
            login = json.load(f)
        url = "postgresql+psycopg2://{user}:{password}@{host}:{port}/{database}".format(
            **login
        )
        _engine = create_engine(url)
    return _engine


